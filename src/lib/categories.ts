export function categoryOf(key: string | undefined): CategoryDef {
  return CATEGORIES.find((c) => c.key === normalizeCategory(key)) ?? CATEGORIES[0];
}

/** 예전 기록의 분류 키를 지금 분류로 맞춘다 */
export function normalizeCategory(key: string | undefined): Category {
  switch (key) {
    case "wealth":
    case "love":
    case "health":
    case "business":
    case "work":
      return key;
    case "career":
    case "exam":
      return "exam";
    case "document":
    case "contract":
      return "contract";
    case "children":
    case "friend":
    case "move":
    case "self":
    case "overall":
    default:
      return "overall";
  }
}

