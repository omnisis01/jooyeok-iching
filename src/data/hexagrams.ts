/** 괘 번호로 유니코드 기호(䷀~䷿) 반환 */
export function hexagramSymbol(number: number): string {
  return String.fromCodePoint(0x4dc0 + number - 1);
}

export function findHexagramByLines(lines: string): Hexagram {
  const found = HEXAGRAMS.find((h) => h.lines === lines);
  if (!found) throw new Error(`Unknown hexagram lines: ${lines}`);
  return found;
}
